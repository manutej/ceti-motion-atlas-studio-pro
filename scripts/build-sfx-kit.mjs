#!/usr/bin/env node
// build-sfx-kit.mjs — v9.2 step 1: vendor/sfx/*.ogg (CC0) → vendor/sfx/manifest.json, vendor/sfx-kit-LICENSES.md, vendor/sfx-kit.js
// The .ogg files were copied by hand from the read-only clone barty-bart/motion-graphics (skills/sound-effects/sfx/kit/* +
// ding/kenney-interface-confirmation-001.ogg); no script from that repo is executed. Mixkit "typing" is never vendored.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'vendor', 'sfx');
const VERIFIED = '2026-10-12';
const CC0 = 'CC0 1.0';
// Per-file author/source rows copied from motion-graphics/skills/sound-effects/LICENSES.md + sfx/manifest.json
export const KIT_SOURCES = [
  { name: 'whoosh', title: 'Whoosh', author: 'qubodup', source: 'https://freesound.org/people/qubodup/sounds/60013/', from: 'kit/whoosh.ogg' },
  { name: 'impact', title: 'soft_impact3', author: 'peoplearehappy', source: 'https://freesound.org/people/peoplearehappy/sounds/841274/', from: 'kit/impact.ogg' },
  { name: 'pop', title: 'POP SFX Neutral', author: 'ethernel0', source: 'https://freesound.org/people/ethernel0/sounds/776016/', from: 'kit/pop.ogg' },
  { name: 'click', title: 'Classic Click', author: 'adh.dreaming', source: 'https://freesound.org/people/adh.dreaming/sounds/671105/', from: 'kit/click.ogg' },
  { name: 'tick', title: 'Click / Tick', author: 'Squirrel_404', source: 'https://freesound.org/people/Squirrel_404/sounds/683048/', from: 'kit/tick.ogg' },
  { name: 'riser', title: 'Cinematic Riser #3 subtle', author: 'BeaconStudio', source: 'https://freesound.org/people/BeaconStudio/sounds/859482/', from: 'kit/riser.ogg' },
  { name: 'ding', title: 'confirmation_001 (Interface Sounds)', author: 'Kenney (kenney.nl)', source: 'https://kenney.nl/assets/interface-sounds', from: 'ding/kenney-interface-confirmation-001.ogg' }
];
// synthesized cue → kit sample (TICK and RISER are kit-only cues)
export const KIT_MAP = { WHOOSH: 'whoosh', THUD: 'impact', CLICK: 'click', BOOP: 'pop', BOING: 'pop', CHORD: 'ding', TICK: 'tick', RISER: 'riser' };

const files = KIT_SOURCES.map((s) => {
  const buf = fs.readFileSync(path.join(DIR, s.name + '.ogg'));
  if (buf.subarray(0, 4).toString('latin1') !== 'OggS') throw new Error('build-sfx-kit: ' + s.name + '.ogg is not an Ogg stream');
  return { ...s, file: 'sfx/' + s.name + '.ogg', license: CC0, verified: VERIFIED, bytes: buf.length, sha256: crypto.createHash('sha256').update(buf).digest('hex'), b64: buf.toString('base64') };
});
const manifest = { version: 1, kit: 'v9.2', license: CC0, verified: VERIFIED, map: KIT_MAP,
  files: files.map(({ b64, ...f }) => f), totalBytes: files.reduce((s, f) => s + f.bytes, 0) };
fs.writeFileSync(path.join(DIR, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

const lic = [
  '# SFX kit licences (vendor/sfx/, inlined as vendor/sfx-kit.js)',
  '',
  'All seven one-shots are **CC0 1.0** (public domain dedication, https://creativecommons.org/publicdomain/zero/1.0/): use, modify and redistribute, including monetised video. Attribution is optional; credit is given below.',
  '',
  'Copied from Bart\'s `motion-graphics` repo (`skills/sound-effects/sfx/kit/*` and `sfx/ding/kenney-interface-confirmation-001.ogg`); rows below are copied from that repo\'s `LICENSES.md` and `sfx/manifest.json`. The sound-pass approach is credited to **Vox (@Voxyz_ai)**. Freesound sounds were verified CC0 per sound page on ' + VERIFIED + '; the Kenney pack licence (License.txt) states CC0. If a source page ever changes its terms, the sha256 below pins the exact bytes shipped.',
  '',
  'Not vendored: the Mixkit `typing` sample (Mixkit licence forbids standalone redistribution).',
  '',
  '| File | Cue(s) | Title | Author | Source | Licence | Verified | Bytes | sha256 |',
  '|---|---|---|---|---|---|---|---|---|',
  ...files.map((f) => `| ${f.file} | ${Object.keys(KIT_MAP).filter((k) => KIT_MAP[k] === f.name).join(', ')} | ${f.title} | ${f.author} | ${f.source} | ${f.license} | ${f.verified} | ${f.bytes} | ${f.sha256} |`),
  ''
].join('\n');
fs.writeFileSync(path.join(ROOT, 'vendor', 'sfx-kit-LICENSES.md'), lic);

const data = files.map((f) => `    ${f.name}: '${f.b64}'`).join(',\n');
const js = `/* vendor/sfx-kit.js — CETI Motion Atlas Studio Pro v9.2 SFX kit. GENERATED by scripts/build-sfx-kit.mjs; do not edit.
 * Seven CC0 one-shots (base64 OGG). Credits + sha256: vendor/sfx-kit-LICENSES.md. Sound-pass approach: Vox (@Voxyz_ai).
 * SFX_KIT.decode(ctx) decodes every sample once per AudioContext (decodeAudioData) and caches the buffers;
 * SFX_KIT.play(ctx, bus, CUE, at, gain) starts the cached sample on \`bus\` and returns [source, gain, duration] or null.
 * Under Node / without decodeAudioData every call is a no-op (null), so the synthesized cue plays alone. */
(function (root) {
  'use strict';
  var DATA = {
${data}
  };
  var MAP = ${JSON.stringify(KIT_MAP)};
  var cache = typeof WeakMap === 'function' ? new WeakMap() : null;
  function bytes(b64) {
    if (typeof root.atob !== 'function') return null;
    var s = root.atob(b64), u = new Uint8Array(s.length);
    for (var i = 0; i < s.length; i++) u[i] = s.charCodeAt(i);
    return u;
  }
  function decode(ctx) {
    if (!ctx || !cache || typeof ctx.decodeAudioData !== 'function') return null;
    var c = cache.get(ctx); if (c) return c.ready;
    c = { buf: {}, ready: null }; cache.set(ctx, c);
    c.ready = Promise.all(Object.keys(DATA).map(function (k) {
      return new Promise(function (res) {
        var u = bytes(DATA[k]), done = function (b) { if (b && !c.buf[k]) c.buf[k] = b; res(b || null); };
        if (!u) return res(null);
        try { var p = ctx.decodeAudioData(u.buffer, done, function () { res(null); }); if (p && p.then) p.then(done, function () { res(null); }); } catch (_e) { res(null); }
      });
    }));
    return c.ready;
  }
  function buffer(ctx, cue) { var c = cache && ctx && cache.get(ctx), k = MAP[String(cue).toUpperCase()]; return (c && k && c.buf[k]) || null; }
  function play(ctx, bus, cue, at, gain) {
    var b = buffer(ctx, cue); if (!b || !bus) return null;
    var s = ctx.createBufferSource(), g = ctx.createGain();
    s.buffer = b; g.gain.value = gain; s.connect(g); g.connect(bus); s.start(at);
    return [s, g, b.duration || 1];
  }
  root.SFX_KIT = { VERSION: '9.2.0', MAP: MAP, names: Object.keys(DATA), decode: decode, buffer: buffer, play: play };
  if (typeof module !== 'undefined' && module.exports) module.exports = root.SFX_KIT;
})(typeof window !== 'undefined' ? window : globalThis);
`;
if (/<\/script/i.test(js)) throw new Error('build-sfx-kit: generated kit contains </script');
fs.writeFileSync(path.join(ROOT, 'vendor', 'sfx-kit.js'), js);
console.log(`sfx-kit: ${files.length} CC0 files, ${manifest.totalBytes} B raw → vendor/sfx-kit.js ${Buffer.byteLength(js)} B`);
